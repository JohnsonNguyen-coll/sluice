import {loadConfig} from './config';
import {SupabaseStore} from './store';
import {RpcGateway} from './chain';
import {createApi} from './api';
import {SupabaseCatalogStore} from './catalog';
import {SupabaseManagedStore} from './managed-store';
import {ManagedHost} from './managed-host';
const config=loadConfig();
const chain=new RpcGateway(config),catalog=new SupabaseCatalogStore(config);
const hosted=new ManagedHost(config,new SupabaseManagedStore(config),catalog,chain);
const stopHosted=hosted.start();
const api=createApi(config,new SupabaseStore(config),chain,Date.now,catalog,hosted);
const server=Bun.serve({hostname:config.host,port:config.port,maxRequestBodySize:32768,fetch:(req,server)=>api(req,server.requestIP(req)?.address||'unknown')});
console.log('Sluice API: '+server.url);
const stop=()=>{void server.stop().then(stopHosted);};
process.on('SIGINT',stop);
process.on('SIGTERM',stop);
